#!/usr/bin/env bash
# SPDX-License-Identifier: MPL-2.0
# Reviewed evidence inventory, not a certification or test runner.
set -euo pipefail
ROOT=${CATALOGUE_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}
ROOT=$(realpath -e "$ROOT")
[[ $# -le 1 && ( ${1:-} == '' || ${1:-} == --check ) ]] || exit 2
inventory=$ROOT/catalogue/capabilities.json
evidence=$ROOT/catalogue/assurance.json
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
jq -e --slurpfile catalogue "$inventory" '
 def text: type=="string" and test("\\S") and (test("[\\x00-\\x1f]")|not);
 . as $a |
 keys==["capabilities","inspected_source","schema_version"] and .schema_version==1 and
 (.inspected_source|type=="string" and test("^[0-9a-f]{40}$")) and
 (.capabilities|type=="array" and length>0) and
 ([.capabilities[].id]|sort)==([$catalogue[0].capabilities[].id]|sort) and
 all(.capabilities[]; . as $row |
  ((.coverage=="placeholder") == ([$catalogue[0].capabilities[]|select(.id==$row.id)|.status][0]=="stub")) and
  ((.coverage=="advisory-only") == ([$catalogue[0].capabilities[]|select(.id==$row.id)|.status][0]=="advisory")) and
  keys==["consumer_receipts","coverage","evidence_note","id","test_paths"] and
  (.id|text) and (.evidence_note|text) and
  (.coverage as $c|["controls-linked","not-assessed","advisory-only","placeholder"]|index($c)!=null) and
  (.test_paths|type=="array") and all(.test_paths[]; text and test("^(actions/|tests/|\\.github/workflows/)") and (split("/")|index("..")|not)) and
  ((.coverage=="controls-linked") == (.test_paths|length>0)) and
  (.consumer_receipts|type=="array") and all(.consumer_receipts[];
   keys==["scope","subject_sha","url"] and (.scope|text) and
   (.subject_sha|type=="string" and test("^[0-9a-f]{40}$")) and
   (.url|type=="string" and test("^https://github.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+/actions/runs/[0-9]+$")))
 )' "$evidence" >/dev/null || { echo 'invalid or incomplete assurance metadata' >&2; exit 1; }
while IFS= read -r path; do
    target=$(realpath -e "$ROOT/$path") || exit 1
    [[ $target == "$ROOT/"* && -f $target ]] || exit 1
done < <(jq -r '.capabilities[].test_paths[]' "$evidence")
jq -r --slurpfile assurance "$evidence" '
 def link($p): "link:../"+$p+"["+$p+"]";
 . as $catalogue | $assurance[0] as $a |
 ["// SPDX-License-Identifier: CC-BY-SA-4.0",
 "// Generated by scripts/build-assurance-matrix.sh; edit catalogue/assurance.json.",
 "= Capability Assurance Matrix", ":toc:", "",
 "Evidence and limits for all \(.capabilities|length) existing actions. No new runtime policy is introduced.", "",
 "Inspected source: `\($a.inspected_source)`. This inventory links control sources, not fresh execution results. A file existing does not prove its tests passed or cover every claim. Unlisted evidence means not assessed here, not that evidence cannot exist.", "",
 "* controls-linked: a specific regression/control source was inspected and linked; no blanket execution claim.",
 "* not-assessed: no specific control source was established in this pass.",
 "* advisory-only: signals, not independent assurance. Simulation/heuristics remain explicit.",
 "* placeholder: unfinished assurance; do not deploy as a completed check.", "",
 "Real consumers are cited separately. Mock/stand-in proof tests are not real prover evidence. Exit/not-applicable contracts vary across legacy actions; do not infer a uniform result protocol from a clade or green job.", "",
 "link:../CATALOGUE.adoc[Visitor atlas] · link:assurance/SUITE-CLOSEOUT.adoc[Suite-first work and external progress]", ""] +
 [.clades[] as $clade | ["== "+$clade.title, ""] +
  [$catalogue.capabilities[] | select(.clade==$clade.id) | . as $c |
   ($a.capabilities[]|select(.id==$c.id)) as $e |
   ["=== "+$c.title, "", "*"+$c.status+" · "+$c.nature+" · "+$e.coverage+"*", "",
    "*Claim:* "+$c.summary, "", "*Prerequisites / boundary:* "+$c.limitations, "",
    "*Control evidence:* "+(if ($e.test_paths|length)==0 then "Not established in this pass." else ([$e.test_paths[]|link(.)]|join("; ")) end), "",
    $e.evidence_note, ""] +
   (if ($e.consumer_receipts|length)==0 then ["*Consumer proof:* no receipt indexed here.", ""] else
    [$e.consumer_receipts[] | "*Consumer proof:* "+.url+"[main run] at `"+.subject_sha+"`. "+.scope, ""] end) | .[]] | .[]] | .[]' "$inventory" > "$tmp/matrix.adoc"
sed -i '${/^$/d;}' "$tmp/matrix.adoc"
page=$ROOT/docs/CAPABILITY-ASSURANCE.adoc
if [[ ${1:-} == --check ]]; then
    cmp -s "$tmp/matrix.adoc" "$page" || { echo 'stale assurance matrix' >&2; exit 1; }
else
    mkdir -p "$ROOT/docs"
    cp "$tmp/matrix.adoc" "$page"
fi
echo 'assurance matrix: inventory, linked control paths and generated page valid'
