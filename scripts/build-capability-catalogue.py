"""Validate the visitor catalogue and render its AsciiDoc discovery pages.

Standard library only. --check is read-only and fails on inventory drift or
stale pages. Classification is reviewed metadata, not inferred assurance.
"""
import argparse
from collections import Counter
import json
import os
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
STATUSES = ("enforcing", "tool-dependent", "advisory", "stub")
NATURES = {"scanner", "receipt-verifier", "policy-gate", "validator", "build-test",
           "proof-executor", "integration", "advisory", "placeholder"}


def validate(data, root=ROOT):
    def require(ok, message):
        if not ok:
            raise ValueError(message)
    require(set(data) == {"schema_version", "clades", "capabilities"}, "unknown catalogue fields")
    require(type(data["schema_version"]) is int and data["schema_version"] == 1, "unsupported catalogue schema")
    require(isinstance(data["clades"], list) and data["clades"], "clades must be a nonempty list")
    require(isinstance(data["capabilities"], list) and data["capabilities"], "capabilities must be a nonempty list")
    ids = set()
    for clade in data["clades"]:
        require(set(clade) == {"id", "title", "summary"}, "invalid clade fields")
        require(all(isinstance(v, str) and v.strip() for v in clade.values()), "empty clade field")
        require(re.fullmatch(r"[a-z][a-z0-9-]*", clade["id"]) is not None, "invalid clade identifier")
        require(clade["id"] not in ids, "duplicate clade")
        ids.add(clade["id"])
    seen, paths, used = set(), set(), set()
    required = {"id", "clade", "status", "nature", "title", "summary", "limitations", "path"}
    for item in data["capabilities"]:
        require(required <= set(item) <= required | {"workflow", "template"}, "invalid capability fields")
        require(all(isinstance(v, str) and v.strip() for v in item.values()), "empty capability field")
        require(re.fullmatch(r"[a-z][a-z0-9-]*", item["id"]) is not None, "invalid capability identifier")
        require(item["id"] not in seen, "duplicate capability")
        seen.add(item["id"])
        require(item["clade"] in ids, "unknown clade")
        used.add(item["clade"])
        require(item["status"] in STATUSES, "unknown assurance status")
        require(item["nature"] in NATURES, "unknown capability nature")
        require((item["status"] == "stub") == (item["nature"] == "placeholder"), "placeholder/status mismatch")
        require(item["path"] == f"actions/{item['id']}-check/action.yml", "capability path/identifier mismatch")
        for field in ("path", "workflow", "template"):
            if field not in item:
                continue
            path = Path(item[field])
            require(not path.is_absolute() and ".." not in path.parts, "unsafe catalogue path")
            target = (root / path).resolve()
            require(target.is_relative_to(root.resolve()) and target.is_file(), "missing or escaping catalogue target: " + str(path))
            if field != "path":
                prefix = ".github/workflows/" if field == "workflow" else "templates/"
                require(item[field].startswith(prefix) and path.suffix == ".yml", "invalid entry-point location")
        require(item["path"] not in paths, "duplicate action path")
        paths.add(item["path"])
    actual = {str(p.relative_to(root)) for p in (root / "actions").glob("*/action.yml")}
    require(paths == actual, f"action inventory drift: missing={sorted(actual-paths)}, extra={sorted(paths-actual)}")
    require(used == ids, "empty clade")


def link(target, label, page):
    return f"link:{os.path.relpath(target, Path(page).parent)}[{label}]"


def render(data):
    entries = data["capabilities"]
    counts = Counter(e["status"] for e in entries)
    page = "CATALOGUE.adoc"
    lines = ["// SPDX-License-Identifier: CC-BY-SA-4.0",
             "// Generated by scripts/build-capability-catalogue.py; edit catalogue/capabilities.json.",
             "= The CI/CD Capability Atlas", ":toc:", ":toclevels: 2", "",
             "*Repository assurance, organised by purpose. Discover by clade; choose by nature; adopt with evidence.*", "",
             f"*{len(entries)} composite actions · {len(data['clades'])} clades · two independent discovery axes.*", "",
             "This is a visitor-facing product catalogue, not a repo-chora file, a BoJ cartridge implementation, or a certification scheme. "
             "Inspired by BoJ's separation of capability domain from interface/type, it groups existing CI/CD building blocks without moving their paths or changing their behaviour.", "",
             "== Find your route", "",
             "* *Protect credentials:* <<sentinel,Sentinel>> — bounded secret scanning and authoritative result receipts.",
             "* *Establish repository policy:* <<covenant,Covenant>>, <<forge,Forge>> and <<schema,Schema>>.",
             "* *Compile, test or prove:* <<proof,Proof>> — language-specific execution and explicitly labelled source checks.",
             "* *Integrate the ecosystem:* <<bridge,Bridge>> — BoJ applicability, Pons and Panic Attack.",
             "* *Explore signals and future work:* <<observatory,Observatory>> and <<frontier,Frontier>> — no inflated assurance claims.", "",
             "== The clade matrix", "", '[cols="2,4,1,1,1,1,1",options="header"]', "|===",
             "|Clade |Purpose |Total |Enforcing |Tool-dependent |Advisory |Stub"]
    for c in data["clades"]:
        group = [e for e in entries if e["clade"] == c["id"]]
        n = Counter(e["status"] for e in group)
        lines.append(f"|<<{c['id']},{c['title']}>> |{c['summary']} |{len(group)} " + " ".join(f"|{n[s]}" for s in STATUSES))
    lines += ["|===", "", "== Read the assurance labels", "",
              f"* *Enforcing ({counts['enforcing']}):* can reject a subject. This is not a guarantee of completeness, applicability, production readiness or formal verification.",
              f"* *Tool-dependent ({counts['tool-dependent']}):* requires explicitly supplied validators/toolchains; inspect applicability and not-run behaviour before adoption.",
              f"* *Advisory ({counts['advisory']}):* signals and warnings, not an assurance verdict. Some current outputs are simulated or heuristic; each card names the boundary.",
              f"* *Stub ({counts['stub']}):* unfinished integration or placeholder. Do not deploy as evidence of a completed check.", "",
              "Nature is a separate axis: a policy-pattern scan is not a compiler, a receipt verifier is not an analyser, and a proof executor is not a proof that every program is correct. "
              "These labels are reviewed inventory metadata; tests enforce coverage and consistency, not semantic correctness of every gate.", ""]
    lines += ["== Browse by nature", "", '[cols="2,1,7",options="header"]', "|===", "|Nature |Count |Capabilities"]
    for nature in sorted(NATURES):
        group = [e for e in entries if e["nature"] == nature]
        if group:
            lines.append(f"|{nature} |{len(group)} |" + " · ".join(link(e["path"], e["title"], page) for e in group))
    lines += ["|===", ""]
    output = {}
    for c in data["clades"]:
        path = f"catalogue/clades/{c['id']}.adoc"
        group = [e for e in entries if e["clade"] == c["id"]]
        lines += [f"[[{c['id']}]]", f"== {c['title']}", "", c["summary"], "",
                  link(path, f"Explore this clade — {len(group)} capabilities", page), "",
                  '[cols="2,2,2,5",options="header"]', "|===", "|Capability |Nature |Status |What it does"]
        cards = ["// SPDX-License-Identifier: CC-BY-SA-4.0",
                 "// Generated by scripts/build-capability-catalogue.py; edit catalogue/capabilities.json.",
                 f"= {c['title']}", ":toc:", "", link("CATALOGUE.adoc", "Back to the Capability Atlas", path), "", c["summary"], ""]
        for e in group:
            lines.append(f"|{link(e['path'], e['title'], page)} |{e['nature']} |{e['status']} |{e['summary']}")
            cards += [f"[[{e['id']}]]", f"== {e['title']}", "",
                      f"*`{e['id']}` · {e['nature']} · {e['status']}*", "", e["summary"], "",
                      f"*Assurance boundary:* {e['limitations']}", "",
                      "* " + link(e["path"], "Action definition and inputs", path)]
            for field, title in (("workflow", "Reusable workflow"), ("template", "Caller template")):
                if field in e:
                    cards.append("* " + link(e[field], title, path))
            cards.append("")
        lines += ["|===", ""]
        output[path] = "\n".join(cards).rstrip() + "\n"
    lines += ["== Adopt deliberately", "",
              "Start with a reusable workflow/caller template where supplied: it handles orchestration that a bare composite may not. "
              "Read the action's inputs, scripts, prerequisites and test controls. Pin an already-published, tested source SHA; update the caller lock and complete dependency closure together. "
              "Never turn unavailable tools, absent analysis or skipped work into a green assurance claim.", "",
              "* " + link("templates/estate-audit-caller.yml", "Estate-audit caller", page),
              "* " + link(".github/workflows/main-estate-audit.yml", "Estate-audit orchestration", page),
              "* " + link("docs/SECRET-SCANNER-ROLLOUT.adoc", "Secret-scanner rollout and security boundaries", page),
              "* " + link("docs/GOVERNANCE-AND-SONAR-REPAIR.adoc", "Governance and Sonar verification guidance", page),
              "* " + link("README.adoc", "Operational README, known defects and test guidance", page), "",
              "== Keep the atlas honest", "",
              "The single inventory is " + link("catalogue/capabilities.json", "catalogue/capabilities.json", page) + ". "
              "Every action must appear exactly once in one primary clade; status and nature remain independent. "
              "Adding an action without cataloguing it, breaking a target link, duplicating an entry or leaving generated pages stale fails the catalogue checks.", "",
              "[source,shell]", "----", "python3 scripts/build-capability-catalogue.py", "python3 scripts/build-capability-catalogue.py --check",
              "python3 tests/capability-catalogue.py", "----", ""]
    output[page] = "\n".join(lines)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        data = json.loads((ROOT / "catalogue/capabilities.json").read_text())
        validate(data, ROOT)
        pages = render(data)
        extra = {str(p.relative_to(ROOT)) for p in (ROOT / "catalogue/clades").glob("*.adoc")} - set(pages)
        if extra:
            raise ValueError("orphan clade pages: " + ", ".join(sorted(extra)))
        for name, content in pages.items():
            path = ROOT / name
            if args.check:
                if not path.is_file() or path.read_text() != content:
                    raise ValueError("stale catalogue page: " + name)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
        print(f"Catalogue {'checked' if args.check else 'rendered'}: {len(data['capabilities'])} actions, {len(data['clades'])} clades")
    except (ValueError, TypeError, KeyError, OSError) as exc:
        parser.exit(1, f"catalogue: {exc}\n")


if __name__ == "__main__":
    main()
